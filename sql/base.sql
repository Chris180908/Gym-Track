-- Instalación desde cero (solo una base de pruebas).
-- ATENCIÓN: ejecutar DROP elimina la base existente.
DROP DATABASE IF EXISTS GYMTRACK;
CREATE DATABASE GYMTRACK CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE GYMTRACK;

CREATE TABLE ROL (
    ID_ROL BIGINT PRIMARY KEY AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR(100)
);

CREATE TABLE USUARIO (
    ID BIGINT PRIMARY KEY AUTO_INCREMENT,
    USERNAME VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    ACTIVO BOOLEAN NOT NULL DEFAULT TRUE,
    ID_ROL BIGINT NOT NULL,
    FOREIGN KEY (ID_ROL) REFERENCES ROL(ID_ROL) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE RECEPCIONISTA (
    ID_RECEPCION BIGINT PRIMARY KEY,
    NOM_RECEPCION VARCHAR(100) NOT NULL,
    NUM_CALLE_R VARCHAR(20),
    COL_R VARCHAR(100),
    EDO_R VARCHAR(100),
    COD_POST_R VARCHAR(10),
    TEL_RECEPCION VARCHAR(15),
    CORREO_RECEPCION VARCHAR(100) UNIQUE,
    FOREIGN KEY (ID_RECEPCION) REFERENCES USUARIO(ID) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE SOCIO (
    ID_SOCIO BIGINT PRIMARY KEY,
    NOM_SOCIO VARCHAR(100) NOT NULL,
    NUM_CALLE_S VARCHAR(20),
    COL_S VARCHAR(100),
    EDO_S VARCHAR(100),
    COD_POST_S VARCHAR(10),
    TEL_SOCIO VARCHAR(15),
    CORREO_SOCIO VARCHAR(100) UNIQUE,
    ESTATUS ENUM('ACTIVO', 'INACTIVO') NOT NULL DEFAULT 'ACTIVO',
    FECHA_REGISTRO DATE NOT NULL DEFAULT (CURRENT_DATE),
    ID_RECEPCION BIGINT NOT NULL,
    FOREIGN KEY (ID_SOCIO) REFERENCES USUARIO(ID) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (ID_RECEPCION) REFERENCES RECEPCIONISTA(ID_RECEPCION) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE PLAN_MEMBRESIA (
    ID_PLAN BIGINT PRIMARY KEY AUTO_INCREMENT,
    NOMBRE VARCHAR(50) NOT NULL,
    PRECIO DECIMAL(10,2) NOT NULL,
    DURACION_MESES INT NOT NULL,
    ACTIVO BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE SUSCRIPCION (
    ID_SUSCRIPCION BIGINT PRIMARY KEY AUTO_INCREMENT,
    ID_SOCIO BIGINT NOT NULL,
    ID_PLAN BIGINT NOT NULL,
    REFERENCIA_EXTERNA VARCHAR(150) UNIQUE,
    PROVEEDOR VARCHAR(50),
    ESTATUS ENUM('PENDIENTE', 'ACTIVA', 'SUSPENDIDA', 'CANCELADA') NOT NULL DEFAULT 'PENDIENTE',
    FECHA_INICIO DATETIME,
    PROXIMO_COBRO DATETIME,
    FOREIGN KEY (ID_SOCIO) REFERENCES SOCIO(ID_SOCIO) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (ID_PLAN) REFERENCES PLAN_MEMBRESIA(ID_PLAN) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE MEMBRESIA (
    ID_MENSUALIDAD BIGINT PRIMARY KEY AUTO_INCREMENT,
    TIPO VARCHAR(50) NOT NULL DEFAULT 'Mensual',
    PRECIO DECIMAL(10,2) NOT NULL,
    FECHA_I DATE NOT NULL,
    FECHA_F DATE NOT NULL,
    ESTATUS ENUM('VIGENTE', 'VENCIDA', 'CANCELADA') NOT NULL DEFAULT 'VIGENTE',
    MODALIDAD ENUM('PREPAGO', 'SUSCRIPCION') NOT NULL DEFAULT 'PREPAGO',
    ID_SOCIO BIGINT NOT NULL,
    ID_PLAN BIGINT NULL,
    ID_SUSCRIPCION BIGINT NULL,
    FOREIGN KEY (ID_SOCIO) REFERENCES SOCIO(ID_SOCIO) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (ID_PLAN) REFERENCES PLAN_MEMBRESIA(ID_PLAN) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (ID_SUSCRIPCION) REFERENCES SUSCRIPCION(ID_SUSCRIPCION) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE PAGO (
    ID_PAGO BIGINT PRIMARY KEY AUTO_INCREMENT,
    MONTO DECIMAL(10,2) NOT NULL,
    FECHA_PAGO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    METODO_PAGO ENUM('EFECTIVO', 'TARJETA', 'TRANSFERENCIA') NOT NULL,
    CONCEPTO VARCHAR(100) NOT NULL,
    ORIGEN ENUM('RECEPCION', 'APP') NOT NULL DEFAULT 'RECEPCION',
    REFERENCIA_EXTERNA VARCHAR(150) UNIQUE,
    PROVEEDOR VARCHAR(50),
    MONEDA CHAR(3) NOT NULL DEFAULT 'MXN',
    ID_MENSUALIDAD BIGINT NOT NULL,
    ID_RECEPCION BIGINT NULL,
    FOREIGN KEY (ID_MENSUALIDAD) REFERENCES MEMBRESIA(ID_MENSUALIDAD) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (ID_RECEPCION) REFERENCES RECEPCIONISTA(ID_RECEPCION) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE REPORTE (
    ID_REPORTE BIGINT PRIMARY KEY AUTO_INCREMENT,
    TIPO_REPORTE ENUM('GENERAL', 'SOCIOS', 'MEMBRESIAS', 'PAGOS') NOT NULL,
    FECHA_INICIO_FILTRO DATE,
    FECHA_FIN_FILTRO DATE,
    FECHA_G DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ID_RECEPCION BIGINT NOT NULL,
    FOREIGN KEY (ID_RECEPCION) REFERENCES RECEPCIONISTA(ID_RECEPCION) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE ACCESO_GYM (
    ID_ACCESO BIGINT PRIMARY KEY AUTO_INCREMENT,
    ID_SOCIO BIGINT NOT NULL,
    FECHA_ACCESO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RESULTADO ENUM('PERMITIDO', 'DENEGADO') NOT NULL,
    FOREIGN KEY (ID_SOCIO) REFERENCES SOCIO(ID_SOCIO) ON DELETE RESTRICT ON UPDATE CASCADE
);

